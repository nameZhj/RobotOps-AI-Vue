import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, relative } from 'node:path'

const root = process.cwd()
const source = join(root, 'src')
const rows = []
async function walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) await walk(path)
    else if (/\.(ts|vue)$/.test(entry.name)) {
      const text = await readFile(path, 'utf8')
      const exports = [...text.matchAll(/export\s+(?:interface|type|class|function|const)\s+([A-Za-z0-9_]+)/g)].map(m => m[1])
      rows.push({ path: relative(root, path), exports: exports.slice(0, 12).join(', ') || '-' })
    }
  }
}
await walk(source)
rows.sort((a, b) => a.path.localeCompare(b.path))
const body = ['# Generated Source Index', '', '> Auto-generated by `npm run ai:index`. Do not hand-edit this file.', '', '| Path | Exported symbols |', '|---|---|', ...rows.map(r => `| \`${r.path}\` | ${r.exports} |`), ''].join('\n')
await writeFile(join(root, '.agent/SOURCE_INDEX.md'), body)
console.log(`Indexed ${rows.length} source files.`)
